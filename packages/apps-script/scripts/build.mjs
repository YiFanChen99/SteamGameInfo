import { execFileSync } from 'node:child_process';
import { copyFile, mkdir, rm } from 'node:fs/promises';
import * as esbuild from 'esbuild';

const outDir = 'dist';
const globalName = 'App';
/** Exports of src/main.ts that Apps Script must see as global functions. */
const entryPoints = ['doGet', 'onEdit', 'WantToOwned'];

function sourceRevision() {
    try {
        const sha = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();
        const dirty = execFileSync('git', ['status', '--porcelain', '--', '.'], { encoding: 'utf8' }).trim();
        return dirty ? `${sha} + uncommitted changes` : sha;
    } catch {
        return 'unknown';
    }
}

const banner = [
    '// ⚠ Generated by game-watchlist-keeper packages/apps-script; do not edit here.',
    '//   clasp push overwrites this whole project from the repo.',
    `//   Source revision: ${sourceRevision()}`,
    '',
].join('\n');

// Apps Script has no modules and only finds top-level function declarations.
const footer = [
    '',
    '// Entry points',
    ...entryPoints.map(name => `function ${name}(...args) { return ${globalName}.${name}(...args); }`),
    '',
].join('\n');

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

await esbuild.build({
    entryPoints: ['src/main.ts'],
    outfile: `${outDir}/Code.js`,
    bundle: true,
    format: 'iife',
    globalName,
    target: 'es2020',
    charset: 'utf8',
    // Deliberately unminified: the Apps Script editor shows this file as-is.
    minify: false,
    banner: { js: banner },
    footer: { js: footer },
});

await copyFile('appsscript.json', `${outDir}/appsscript.json`);

console.log(`Built ${outDir}/Code.js (${entryPoints.join(', ')})`);
